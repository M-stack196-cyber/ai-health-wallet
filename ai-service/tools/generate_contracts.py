"""Generate code-only contract data/types; --check never writes files."""
from pathlib import Path
import json,sys
root=Path(__file__).resolve().parents[2]
shared=root/'shared/medical-summary'
schema=json.loads((shared/'v1.schema.json').read_text())
glossary=json.loads((shared/'glossary-v1.json').read_text())
def annotation(r):
 if '$ref' in r:return r['$ref'].split('/')[-1]
 if 'const' in r:return 'Literal['+repr(r['const'])+']'
 if 'enum' in r:return 'Literal['+', '.join(repr(v) for v in r['enum'])+']'
 if 'anyOf' in r:return ' | '.join(annotation(x) for x in r['anyOf'])
 if r['type']=='array':return 'list['+annotation(r['items'])+']'
 return {'string':'str','integer':'int','boolean':'bool','null':'None'}[r['type']]
lines=['# Generated by tools/generate_contracts.py. Do not edit.','from __future__ import annotations','from typing import TypedDict, Literal','']
for name,rule in schema['$defs'].items():
 if rule.get('type')=='object':
  lines.append('class '+name+'(TypedDict):')
  for key,r in rule['properties'].items():lines.append('    '+key+': '+annotation(r))
  lines.append('')
names={'Scope':'SummaryScopeV1','Evidence':'EvidenceV1','QuotedText':'QuotedTextV1','DecimalValue':'DecimalValueV1','Operator':'ReportedOperatorV1','ReportedFlag':'ReportedFlagV1','Measurement':'MeasurementV1','Fact':'ReportedFactV1','Source':'SummarySourceV1','Uncertainty':'SummaryUncertaintyV1'}
def ts_type(r):
 if '$ref' in r:
  name=r['$ref'].split('/')[-1];return names.get(name,name)
 if 'const' in r:return json.dumps(r['const'],ensure_ascii=False)
 if 'enum' in r:return ' | '.join(json.dumps(x,ensure_ascii=False) for x in r['enum'])
 if 'anyOf' in r:return ' | '.join(ts_type(x) for x in r['anyOf'])
 if r['type']=='array':return '('+ts_type(r['items'])+')[]'
 return {'string':'string','integer':'number','boolean':'boolean','null':'null'}[r['type']]
ts=['// Generated by ai-service/tools/generate_contracts.py. Do not edit.']
for name,rule in schema['$defs'].items():
 if rule.get('type')=='object':
  ts.append('export interface '+names.get(name,name)+' {')
  for key,r in rule['properties'].items():ts.append('  '+key+': '+ts_type(r)+';')
  ts.append('}')
ts.extend(["export type EducationId = SummaryOutputV1['educational_explanations'][number];","export type UncertaintyCode = SummaryOutputV1['uncertainty']['codes'][number];",'// Expected identity is supplied by trusted authorization/snapshot code, never the model.','export interface SummaryValidationContext extends SummaryScopeV1 {input_sha256:string;}'])
outputs={root/'backend/src/summaries/contracts.ts':'\n'.join(ts)+'\n',root/'backend/src/summaries/schema.generated.ts':'// Generated by ai-service/tools/generate_contracts.py. Do not edit.\nexport const SCHEMA = '+json.dumps(schema,ensure_ascii=False,indent=2)+' as const;\nexport const GLOSSARY = '+json.dumps(glossary,ensure_ascii=False,indent=2)+' as const;\nfunction freeze(value:unknown):void {if(value!==null&&typeof value===\"object\"){Object.values(value).forEach(freeze);Object.freeze(value);}}\nfreeze(SCHEMA);freeze(GLOSSARY);\n',root/'ai-service/summary_contracts/types.py':'\n'.join(lines)+'\n'}
for path,text in outputs.items():
 if '--check' in sys.argv:
  if not path.is_file() or path.read_text()!=text:raise SystemExit('Generated summary contract drift detected.')
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
if '--check' in sys.argv:print('PASS: generated contracts match canonical schema/glossary.')
